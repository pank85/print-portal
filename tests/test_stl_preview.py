"""The pre-slice STL preview serves the job's STL and never the sliced gcode."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "app" / "index.html"
VIEWER = ROOT / "app" / "vendor" / "model-viewer" / "index.html"


def _job(jobs_dir: Path, jid: str, **fields) -> Path:
    directory = jobs_dir / jid
    (directory / "upload").mkdir(parents=True)
    (directory / "job.json").write_text(json.dumps({"id": jid, **fields}))
    return directory


def test_the_jobs_page_has_a_separate_stl_preview():
    page = PAGE.read_text()
    assert '<h2 id="stlPreviewTitle" tabindex="-1">STL preview</h2>' in page
    assert 'id="stlPreviewFrame"' in page
    assert 'title="STL model preview"' in page
    assert "/vendor/model-viewer/index.html" in page
    assert 'type:"load_model"' in page
    assert 'ext:"stl"' in page
    assert "openStlPreview(btn.dataset.ref, btn)" in page
    assert "initStlPreview();" in page
    row = page[page.index("function renderJobRow"):page.index("function setUploadLatest")]
    assert 'data-act="stl-preview"' in row
    assert "${stlPreview}" in row
    assert row.index("${stlPreview}") < row.index("${actions}")


def test_the_vendored_viewer_does_not_fetch_a_cdn():
    viewer = VIEWER.read_text()
    for banned in ("esm.sh", "jsdelivr", "cdnjs", "occt-import-js", "https://", "http://", "fetch("):
        assert banned not in viewer
    assert 'from "three"' in viewer
    assert "./three/OrbitControls.js" in viewer
    assert "./three/STLLoader.js" in viewer
    assert "TransformControls" not in viewer
    assert (VIEWER.parent / "LICENSE").is_file()
    assert (VIEWER.parent / "three" / "LICENSE").is_file()
    assert (VIEWER.parent / "three" / "VERSION").read_text().strip() == "0.160.0"


def test_stl_endpoint_returns_the_upload_not_gcode(client, jobs_dir, sliced_dir, cube_stl):
    directory = _job(
        jobs_dir, "decafbad1234", status="sliced", filename="cube.stl", gcode="cube.gcode",
    )
    (directory / "upload" / "cube.stl").write_bytes(cube_stl)
    sliced = sliced_dir / "decafbad1234"
    sliced.mkdir()
    (sliced / "cube.gcode").write_text("; total filament used [g] = 3.94\nG1 X1\n")

    response = client.get("/api/jobs/decafbad1234/stl")

    assert response.status_code == 200
    assert response.content == cube_stl
    assert response.headers["content-type"].startswith("model/stl")
    assert "cube.stl" in response.headers["content-disposition"]
    assert b"G1" not in response.content
    assert client.get("/api/jobs/decafbad1234/gcode").text.startswith("; total filament")


def test_stl_endpoint_uses_the_original_after_a_derived_3mf(client, jobs_dir, cube_stl):
    directory = _job(
        jobs_dir, "decafbad1234", status="awaiting_confirm",
        filename="fins-cube.3mf", original="cube.stl",
    )
    (directory / "upload" / "cube.stl").write_bytes(cube_stl)
    (directory / "upload" / "fins-cube.3mf").write_bytes(b"PK\x03\x04not-the-stl")

    response = client.get("/api/jobs/decafbad1234/stl")

    assert response.status_code == 200
    assert response.content == cube_stl


def test_stl_endpoint_refuses_a_job_without_an_stl(client, jobs_dir, sliced_dir):
    directory = _job(jobs_dir, "decafbad1234", status="sliced", filename="model.3mf", gcode="model.gcode")
    (directory / "upload" / "model.3mf").write_bytes(b"not an archive")
    sliced = sliced_dir / "decafbad1234"
    sliced.mkdir()
    (sliced / "model.gcode").write_text("G28\nG1 X1\n")

    response = client.get("/api/jobs/decafbad1234/stl")

    assert response.status_code == 409
    assert response.json()["detail"] == "this job has no STL"
    assert b"G28" not in response.content
    assert client.get("/api/jobs/decafbad1234/gcode").text.startswith("G28")


def test_stl_endpoint_refuses_gcode_renamed_to_stl(client, jobs_dir):
    directory = _job(jobs_dir, "decafbad1234", status="awaiting_confirm", filename="cube.stl")
    (directory / "upload" / "cube.stl").write_bytes(b"; generated by slicer\nG28\nG1 X1 Y1\n")

    response = client.get("/api/jobs/decafbad1234/stl")

    assert response.status_code == 409
    assert response.json()["detail"] == "this job has no STL"
    assert b"G28" not in response.content


def test_stl_endpoint_refuses_a_symlink_outside_the_upload(client, jobs_dir):
    directory = _job(jobs_dir, "decafbad1234", status="awaiting_confirm", filename="cube.stl")
    outside = jobs_dir / "secret.stl"
    outside.write_text("not for the viewer\n")
    (directory / "upload" / "cube.stl").symlink_to(outside)

    response = client.get("/api/jobs/decafbad1234/stl")

    assert response.status_code == 409
    assert response.json()["detail"] == "this job has no STL"
    assert b"not for the viewer" not in response.content


def test_vendor_viewer_is_served_locally(client):
    response = client.get("/vendor/model-viewer/index.html")

    assert response.status_code == 200
    assert "esm.sh" not in response.text
    assert "jsdelivr" not in response.text
    assert "cdnjs" not in response.text
    assert "https://" not in response.text
    three = client.get("/vendor/model-viewer/three/three.module.js")
    assert three.status_code == 200
    assert "Copyright" in three.text[:400]
