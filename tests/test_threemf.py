def test_missing_member_yields_empty_info(zip_bytes):
    """No metadata, per-object configs only, or a corrupt JSON member: all empty, no raise."""
    empty = threemf.ThreeMfInfo()
    assert threemf.read_info(zip_bytes({"3D/3dmodel.model": b"<model/>"})) == empty
    # object/part configs describe objects, never the project identity
    assert threemf.read_info(zip_bytes({
        "Metadata/model_settings.config": b"<config><object id='1'/></config>",
        "Metadata/Slic3r_PE_model.config": b"<config/>",
    })) == empty
    assert threemf.read_info(zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: b"{not json"})) == empty
    assert threemf.read_info(zip_bytes({})) == empty


def test_non_zip_bytes_yield_empty_info(three_mf_bytes, write_bytes_fixture, tmp_path):
    empty = threemf.ThreeMfInfo()
    assert threemf.read_info(b"") == empty
    assert threemf.read_info(b"PK\x03\x04 definitely not a zip") == empty
    assert threemf.read_info(three_mf_bytes()[:120]) == empty          # truncated archive
    absent = write_bytes_fixture(tmp_path, "gone.3mf", b"")
    absent.unlink()
    assert threemf.read_info(absent) == empty                          # unreadable path


def test_oversized_settings_member_is_treated_as_missing(zip_bytes):
    """A member that inflates past `MEMBER_MAX_BYTES` is ignored, not decompressed.

    The padding is what a hostile export looks like: a few KB of zip that asks for hundreds
    of MB once inflated, with a valid identity in front of it so that "read it anyway"
    would look like it worked. An identity member is a few KB, so the small control below
    is the same shape that must still be read.
    """
    def settings(pad: int) -> bytes:
        return json.dumps({"printer_settings_id": [MACHINE_NAME],
                           "print_settings_id": [PROCESS_NAME],
                           "pad": "x" * pad}).encode()

    oversized = zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: settings(threemf.MEMBER_MAX_BYTES)})
    assert threemf.read_info(oversized) == threemf.ThreeMfInfo()

    modest = zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: settings(1024)})
    assert (threemf.read_info(modest).printer, threemf.read_info(modest).process) == (
        MACHINE_NAME, PROCESS_NAME)


def test_a_member_header_that_understates_its_size_is_cut_at_the_cap():
    """The header's size is not trusted: the read itself stops one byte past the cap.

    zipfile writes the true size, so a header that lies cannot be produced with it; this
    stands in for one: `file_size` claims nothing while `read` would inflate past the cap.
    """
    class LyingArchive:
        def getinfo(self, name: str) -> object:
            return type("Header", (), {"file_size": 0})()

        def open(self, name: str) -> io.BytesIO:
            return io.BytesIO(b"{" * (threemf.MEMBER_MAX_BYTES + 1))

    index = {threemf.PROJECT_SETTINGS_MEMBER.lower(): threemf.PROJECT_SETTINGS_MEMBER}
    assert threemf._member_bytes(LyingArchive(), index, threemf.PROJECT_SETTINGS_MEMBER) is None


@pytest.mark.parametrize("error", [MemoryError("cannot allocate"), zlib.error("bad deflate")])
def test_archive_errors_degrade_to_no_identity(three_mf_bytes, error, monkeypatch):
    """An allocation or inflate failure inside a member read is a miss, never a 500."""
    blob = three_mf_bytes()
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}

    def explode(self, name, *args, **kwargs):
        raise error

    monkeypatch.setattr(zipfile.ZipFile, "open", explode)
    assert threemf.read_info(blob) == threemf.ThreeMfInfo()
    assert threemf.rewrite_identity(blob, machine, {"name": PROCESS_NAME}) == (blob, "none")


