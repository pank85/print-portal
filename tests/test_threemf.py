def test_rewrite_identity_sets_printer_and_process_ids(zip_bytes, three_mf_bytes):
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}
    process = {"name": PROCESS_NAME}
    blob = zip_bytes({
        "3D/3dmodel.model": b"<model/>",
        threemf.PROJECT_SETTINGS_MEMBER: json.dumps({
            "printer_settings_id": ["Foreign Machine"],
            "printer_model": ["Foreign Model"],
            "printer_variant": ["0.6"],
            "print_settings_id": ["Foreign Process"],
            "compatible_printers": ["Foreign Machine"],
            "layer_height": ["0.28"],
        }).encode(),
    })
    rewritten, outcome = threemf.rewrite_identity(blob, machine, process)
    assert outcome == "identity"
    data = settings_of(rewritten)
    assert data["printer_settings_id"] == [MACHINE_NAME]
    assert data["printer_model"] == [MACHINE_MODEL]
    assert data["printer_variant"] == ["0.4"]
    assert data["print_settings_id"] == [PROCESS_NAME]
    assert data["compatible_printers"] == [MACHINE_NAME]
    assert data["layer_height"] == ["0.28"]          # every other key survives

    # the PrusaSlicer-style member is rewritten in its own syntax when it is the one present
    ini = three_mf_bytes(settings_member="Slic3r_PE.config", printer="Prusa MK4 0.4 nozzle",
                         printer_model="Prusa MK4", process="0.20mm SPEED @MK4")
    rewritten, outcome = threemf.rewrite_identity(ini, machine, process)
    assert outcome == "identity"
    text = members(rewritten)[threemf.SLIC3R_PE_MEMBER].decode()
    assert "printer_settings_id = Generic Klipper 0.4 nozzle" in text
    assert "print_settings_id = 0.20mm Standard @Generic Klipper" in text
    assert "compatible_printers = Generic Klipper 0.4 nozzle" in text
    assert "Foreign" not in text and "Prusa MK4" not in text


def test_rewrite_identity_preserves_other_members(three_mf_bytes):
    """Geometry, plates and thumbnails must survive untouched, in the same order."""
    blob = three_mf_bytes(extra={
        "Metadata/custom_gcode_per_layer.xml": b"<custom_gcodes_per_layer/>",
        "Metadata/plate_1.png": b"\x89PNG\r\n\x1a\nnot really a png",
        "3D/Objects/object_1.model": b"<model><resources/></model>",
    })
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}
    rewritten, outcome = threemf.rewrite_identity(blob, machine, {"name": PROCESS_NAME})
    assert outcome == "identity"
    before, after = members(blob), members(rewritten)
    assert list(after) == list(before)
    with zipfile.ZipFile(io.BytesIO(rewritten)) as zf:
        assert zf.testzip() is None
    for name, data in before.items():
        if name == threemf.PROJECT_SETTINGS_MEMBER:
            assert after[name] != data
        else:
            assert after[name] == data


def test_rewrite_identity_copies_a_member_larger_than_the_cap(three_mf_bytes):
    """The cap protects the reader, not the copy: a big geometry member must survive.

    A model member can legitimately exceed `MEMBER_MAX_BYTES`, and it is the heaviest thing
    in the archive. Dropping it would hand the slicer a broken project; reading it whole
    would reintroduce the memory problem — so it is streamed and kept byte for byte.
    """
    geometry = b"<model>" + b"<v/>" * (threemf.MEMBER_MAX_BYTES // 4) + b"</model>"
    assert len(geometry) > threemf.MEMBER_MAX_BYTES
    blob = three_mf_bytes(extra={"3D/Objects/object_1.model": geometry})
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}

    rewritten, outcome = threemf.rewrite_identity(blob, machine, {"name": PROCESS_NAME})
    assert outcome == "identity"
    assert members(rewritten)["3D/Objects/object_1.model"] == geometry
    assert settings_of(rewritten)["printer_settings_id"] == [MACHINE_NAME]
    with zipfile.ZipFile(io.BytesIO(rewritten)) as zf:
        assert zf.testzip() is None


def test_rewrite_identity_leaves_an_oversized_settings_member_alone(zip_bytes):
    """A settings member past the cap cannot be re-identified, so the upload is sliced as-is."""
    oversized = json.dumps({"printer_settings_id": [MACHINE_NAME],
                            "pad": "x" * threemf.MEMBER_MAX_BYTES}).encode()
    blob = zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: oversized})
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}
    assert threemf.rewrite_identity(blob, machine, {"name": PROCESS_NAME}) == (blob, "none")


def test_rewrite_identity_is_a_noop_without_settings_members(zip_bytes, three_mf_bytes, monkeypatch):
    machine = {"name": MACHINE_NAME, "printer_model": MACHINE_MODEL, "printer_variant": "0.4"}
    plain = zip_bytes({"3D/3dmodel.model": b"<model/>"})
    assert threemf.rewrite_identity(plain, machine, {"name": PROCESS_NAME}) == (plain, "none")
    assert threemf.rewrite_identity(b"not a zip", machine, None) == (b"not a zip", "none")
    unchanged = three_mf_bytes()
    assert threemf.rewrite_identity(unchanged, None, None) == (unchanged, "none")

    # the documented -17 fallback: drop the settings members, keep everything else
    monkeypatch.setattr(threemf, "STRIP", True)
    stripped, outcome = threemf.rewrite_identity(unchanged, machine, {"name": PROCESS_NAME})
    assert outcome == "stripped"
    assert threemf.PROJECT_SETTINGS_MEMBER not in members(stripped)
    assert members(stripped)["3D/3dmodel.model"] == members(unchanged)["3D/3dmodel.model"]


def test_strict_rewrite_validates_and_preserves_geometry(zip_bytes):
    geometry = b'<model>geometry</model>'
    blob = zip_bytes({'3D/3dmodel.model': geometry,
                      threemf.PROJECT_SETTINGS_MEMBER: b'{"printer_settings_id":["old"]}'})
    rewritten, outcome = threemf.rewrite_identity_strict(
        blob, {'name': 'local printer'}, {'name': 'local process'})
    assert outcome == 'identity'
    assert members(rewritten)['3D/3dmodel.model'] == geometry
    assert settings_of(rewritten)['printer_settings_id'] == ['local printer']
    plain = zip_bytes({'3D/3dmodel.model': geometry})
    assert threemf.rewrite_identity_strict(plain, {'name': 'm'}, {'name': 'p'}) == (plain, 'none')


def test_strict_rewrite_rejects_invalid_oversized_and_duplicate_settings(zip_bytes, monkeypatch):
    machine, process = {'name': 'm'}, {'name': 'p'}
    for value in (b'{broken', b'[]', b'\xff'):
        blob = zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: value})
        with pytest.raises(threemf.IdentityPreflightError):
            threemf.rewrite_identity_strict(blob, machine, process)
    with pytest.raises(threemf.IdentityPreflightError):
        threemf.rewrite_identity_strict(zip_bytes({threemf.SLIC3R_PE_MEMBER: b'not ini'}), machine, process)
    monkeypatch.setattr(threemf, 'MEMBER_MAX_BYTES', 5)
    with pytest.raises(threemf.IdentityPreflightError):
        threemf.rewrite_identity_strict(zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: b'{"x":1}'}), machine, process)
    output = io.BytesIO()
    with zipfile.ZipFile(output, 'w') as archive:
        archive.writestr(threemf.PROJECT_SETTINGS_MEMBER, '{}')
        archive.writestr(threemf.PROJECT_SETTINGS_MEMBER.upper(), '{}')
    with pytest.raises(threemf.IdentityPreflightError):
        threemf.rewrite_identity_strict(output.getvalue(), machine, process)
    with pytest.raises(threemf.IdentityPreflightError):
        threemf.rewrite_identity_strict(b'not a zip', machine, process)


def test_strict_rewrite_honors_strip(zip_bytes, monkeypatch):
    monkeypatch.setattr(threemf, 'STRIP', True)
    blob = zip_bytes({threemf.PROJECT_SETTINGS_MEMBER: b'{}', '3D/3dmodel.model': b'geometry'})
    result, outcome = threemf.rewrite_identity_strict(blob, {'name': 'm'}, {'name': 'p'})
    assert outcome == 'stripped'
    assert members(result) == {'3D/3dmodel.model': b'geometry'}


