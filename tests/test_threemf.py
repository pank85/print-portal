def test_matches_machine_by_exact_name(datadir, three_mf_bytes):
    machines = prof.list_presets(datadir)["machine"]
    got = threemf.match_machine(machines, threemf.read_info(three_mf_bytes()))
    assert got is not None
    assert (got["name"], got["rel"]) == (MACHINE_NAME, MACHINE_REL)
    # case and underscores are not identity
    assert threemf.match_machine(machines, threemf.ThreeMfInfo(printer=MACHINE_NAME.upper())) is not None


