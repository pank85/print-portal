"""threemf.py: reading, matching and re-identifying the presets a 3MF names.

Pure functions only. Payloads come from the shared ``three_mf_bytes``/``zip_bytes``
builders, so nothing here touches the network, the printer store or the slicer.
"""
from __future__ import annotations

import io
import json
import zipfile
import zlib

import pytest

import profiles as prof
import threemf

MACHINE_NAME = "Generic Klipper 0.4 nozzle"
MACHINE_MODEL = "Generic Klipper Printer"
PROCESS_NAME = "0.20mm Standard @Generic Klipper"
MACHINE_REL = "system/Custom/machine/generic-klipper-0.4.json"


def members(blob: bytes) -> dict[str, bytes]:
    """Every member of a zip blob, for comparing two archives byte by byte."""
    with zipfile.ZipFile(io.BytesIO(blob)) as zf:
        return {name: zf.read(name) for name in zf.namelist()}


def settings_of(blob: bytes) -> dict:
    return json.loads(members(blob)[threemf.PROJECT_SETTINGS_MEMBER])


# --------------------------------------------------------------------------- reading

def test_reads_project_settings_identity(zip_bytes, write_bytes_fixture, tmp_path):
    """Real exports use strings as well as one-element lists; a Path works like bytes."""
    blob = zip_bytes({
        "3D/3dmodel.model": b"<model/>",
        threemf.PROJECT_SETTINGS_MEMBER: json.dumps({
            "printer_settings_id": MACHINE_NAME,
            "printer_model": MACHINE_MODEL,
            "printer_variant": "0.4",
            "print_settings_id": PROCESS_NAME,
            "filament_settings_id": "Generic PLA",
        }).encode(),
    })
    path = write_bytes_fixture(tmp_path, "foreign.3mf", blob)
    assert threemf.read_info(path) == threemf.ThreeMfInfo(
        printer=MACHINE_NAME,
        printer_model=MACHINE_MODEL,
        printer_variant="0.4",
        process=PROCESS_NAME,
        filaments=("Generic PLA",),
        source=threemf.PROJECT_SETTINGS_MEMBER,
    )


def test_reads_list_valued_identity_keys(three_mf_bytes):
    """One-element lists (the shape the builder writes, like OrcaSlicer) are unwrapped."""
    got = threemf.read_info(three_mf_bytes(filaments=("Generic PLA", "Generic PETG")))
    assert (got.printer, got.process) == (MACHINE_NAME, PROCESS_NAME)
    assert (got.printer_model, got.printer_variant) == (MACHINE_MODEL, "0.4")
    assert got.filaments == ("Generic PLA", "Generic PETG")
    assert got.source == threemf.PROJECT_SETTINGS_MEMBER


def test_falls_back_to_slic3r_pe_config(three_mf_bytes, zip_bytes):
    """A PrusaSlicer-style ini is read when the JSON member carries no identity."""
    blob = three_mf_bytes(settings_member="Slic3r_PE.config", printer="Prusa MK4 0.4 nozzle",
                          printer_model="Prusa MK4", variant="0.4",
                          process="0.20mm SPEED @MK4", filaments=("Prusa PLA",))
    got = threemf.read_info(blob)
    assert (got.printer, got.printer_model) == ("Prusa MK4 0.4 nozzle", "Prusa MK4")
    assert (got.printer_variant, got.process) == ("0.4", "0.20mm SPEED @MK4")
    assert got.filaments == ("Prusa PLA",)
    assert got.source == threemf.SLIC3R_PE_MEMBER

    # a JSON member that names only the filament lets the ini supply the rest, key by key
    blob = zip_bytes({
        threemf.PROJECT_SETTINGS_MEMBER: json.dumps({"filament_settings_id": ["Prusa PLA"]}).encode(),
        threemf.SLIC3R_PE_MEMBER: b"# generated by PrusaSlicer\nprinter_settings_id = Prusa MK4 0.4 nozzle\n"
                                  b"print_settings_id = 0.20mm SPEED @MK4\n",
    })
    got = threemf.read_info(blob)
    assert (got.printer, got.process) == ("Prusa MK4 0.4 nozzle", "0.20mm SPEED @MK4")
    assert got.filaments == ("Prusa PLA",)


